<#
.SYNOPSIS
  Menanamkan function 'local' ke profil PowerShell Pengguna ($PROFILE)
  sehingga dapat langsung mengetik 'local' di terminal PowerShell manapun.

.PARAMETER ProfilePaths
  Daftar path file profil kustom yang ingin dipasang/diperbarui.
  Jika tidak diisi, installer otomatis memeriksa profil PowerShell standar.

.PARAMETER SkipBunCheck
  Lewati pemeriksaan keberadaan runtime Bun di PATH saat instalasi.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts/install-local-cmd.ps1
#>

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string[]]$ProfilePaths,

    [Parameter()]
    [switch]$SkipBunCheck
)

$ErrorActionPreference = "Stop"

# 1. Pemeriksaan Bun Runtime
if (-not $SkipBunCheck -and -not (Get-Command bun -ErrorAction SilentlyContinue)) {
    Write-Error "❌ Bun runtime tidak ditemukan di PATH. Silakan instal Bun (https://bun.sh) terlebih dahulu."
    exit 1
}

# 2. Resolusi Checkout dan Path Skrip
$ScriptDir = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
$RootDir = (Resolve-Path (Join-Path $ScriptDir "..")).Path
$LocalTs = Join-Path $RootDir "scripts\local.ts"

if (-not (Test-Path -LiteralPath $LocalTs)) {
    Write-Error "❌ File target tidak ditemukan di checkout: $LocalTs"
    exit 1
}

# 3. Penyiapan Managed Block
$ManagedBlockStart = "# >>> GLOBAL FHIR LAB LOCAL RUNNER (MANAGED BLOCK) >>>"
$ManagedBlockEnd   = "# <<< GLOBAL FHIR LAB LOCAL RUNNER (MANAGED BLOCK) <<<"

$escapedRootDir = $RootDir.Replace("'", "''")
$escapedLocalTs = $LocalTs.Replace("'", "''")

$ManagedBlock = @"
$ManagedBlockStart
# ===============================================================
# Global HL7 FHIR Learning Lab — PowerShell Shortcuts
# Managed block generated by scripts/install-local-cmd.ps1
# Supports coexistence with Gomoku Space (projects-game).
# ===============================================================

# 1. Dedicated FHIR dev server runner
function local-fhir {
    [CmdletBinding()]
    param(
        [Parameter(ValueFromRemainingArguments = `$true)]
        [string[]]`$Arguments
    )
    Push-Location '$escapedRootDir'
    try {
        if (`$Arguments -and `$Arguments.Count -gt 0) {
            & bun '$escapedLocalTs' @Arguments
        } else {
            & bun '$escapedLocalTs'
        }
    } finally {
        Pop-Location
    }
}

# 2. Quick navigation / CLI launcher for projects-fhir
function fhir {
    param()
    Set-Location '$escapedRootDir'
    if (Get-Command agy -ErrorAction SilentlyContinue) {
        agy @args
    }
}

# 3. Smart Context-Aware 'local' dispatcher:
#    Detects current location. If inside projects-fhir, runs FHIR local runner.
#    Otherwise delegates to projects-game runner if available.
function local {
    [CmdletBinding()]
    param(
        [Parameter(ValueFromRemainingArguments = `$true)]
        [string[]]`$Arguments
    )
    `$currentPath = (Get-Location).Path
    if (`$currentPath -like "$escapedRootDir*" -or (Test-Path (Join-Path `$currentPath "src\types\fhir-global.ts"))) {
        Push-Location '$escapedRootDir'
        try {
            & bun '$escapedLocalTs' @Arguments
        } finally {
            Pop-Location
        }
    } elseif (Test-Path "d:\DEVELOPMENT\projects-game\scripts\local.ts") {
        Push-Location "d:\DEVELOPMENT\projects-game"
        try {
            & bun "d:\DEVELOPMENT\projects-game\scripts\local.ts" @Arguments
        } finally {
            Pop-Location
        }
    } else {
        # Fallback to local script in current directory if present
        if (Test-Path ".\scripts\local.ts") {
            & bun ".\scripts\local.ts" @Arguments
        } else {
            Write-Error "Tidak ditemukan runner 'scripts/local.ts' pada direktori aktif."
        }
    }
}
$ManagedBlockEnd
"@

# 4. Target Profil PowerShell
if (-not $ProfilePaths -or $ProfilePaths.Count -eq 0) {
    $targets = @()
    if ($PROFILE) {
        if ($PROFILE -is [string]) {
            $targets += $PROFILE
        } else {
            if ($PROFILE.CurrentUserCurrentHost) { $targets += $PROFILE.CurrentUserCurrentHost }
            if ($PROFILE.CurrentUserAllHosts)    { $targets += $PROFILE.CurrentUserAllHosts }
        }
    }
    $ProfilePaths = $targets | Select-Object -Unique
}

if (-not $ProfilePaths -or $ProfilePaths.Count -eq 0) {
    Write-Warning "⚠️ Tidak ditemukan file profil PowerShell standar."
    exit 0
}

foreach ($target in $ProfilePaths) {
    $parentDir = Split-Path -Parent $target
    if (-not (Test-Path -LiteralPath $parentDir)) {
        New-Item -ItemType Directory -Path $parentDir -Force | Out-Null
    }

    $existingContent = if (Test-Path -LiteralPath $target) {
        [System.IO.File]::ReadAllText($target)
    } else {
        ""
    }

    if ($existingContent -match [regex]::Escape($ManagedBlockStart)) {
        $pattern = "(?s)" + [regex]::Escape($ManagedBlockStart) + ".*?" + [regex]::Escape($ManagedBlockEnd) + "\r?\n?"
        $updated = [regex]::Replace($existingContent, $pattern, $ManagedBlock + "`r`n")
        [System.IO.File]::WriteAllText($target, $updated)
        Write-Host "✅ Diperbarui: $target"
    } else {
        $sep = if ($existingContent.Length -gt 0 -and -not $existingContent.EndsWith("`n")) { "`r`n" } else { "" }
        [System.IO.File]::WriteAllText($target, $existingContent + $sep + $ManagedBlock + "`r`n")
        Write-Host "✅ Berhasil dipasang: $target"
    }
}

Write-Host "`n🎉 Command 'local' berhasil dipasang ke profil PowerShell!"
Write-Host "   Buka terminal baru atau jalankan: . `$PROFILE"
